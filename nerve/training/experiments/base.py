"""
Base configuration class for all NERVE training experiments.
This provides a unified configuration system for YOLOX, YOLOv8, and ReYOLOv8.

Usage:
    Inherit from YOLOXBase, YOLOv8Base, or ReYOLOv8Base and override parameters.
"""

import os
from pathlib import Path
from abc import ABC, abstractmethod


class BaseConfig(ABC):
    """
    Abstract base configuration class for all experiments.
    Provides common parameters and interface for all model types.
    """
    
    # Model type identifier (set by subclasses)
    MODEL_TYPE = None  # 'yolox', 'yolov8', or 'reyolov8'
    
    def __init__(self, dataset_path: str = None, data_yaml: str = None):
        """
        Initialize base configuration.
        
        Args:
            dataset_path: Path to dataset root directory
            data_yaml: Path to data.yaml file (for YOLOv8/ReYOLOv8)
        """
        # Dataset Configuration
        self.dataset_path = dataset_path
        self.data_yaml = data_yaml  # Path to data.yaml (auto-generated by dataset_creator.py)
        
        # Task Configuration
        self.include_radar = False          # Use radar point cloud data
        self.process_distance = False       # Enable distance estimation
        self.distance_from_head = True      # Predict distance from head vs extract from radar
        
        # Distance Parameters
        self.min_distance = 0.0
        self.max_distance = 10.0
        self.nbins = 100  # Number of distance bins for classification
        self.distance_loss_multiplier = 1.0
        
        # Model Configuration
        self.num_classes = 1
        self.class_names = ['person']
        
        # Training Configuration
        self.epochs = 100
        self.batch_size = 16
        self.imgsz = 416  # Input image size
        self.workers = 8  # Number of dataloader workers
        
        # Optimization
        self.lr0 = 0.01  # Initial learning rate
        self.momentum = 0.937
        self.weight_decay = 0.0005
        self.warmup_epochs = 3
        
        # Augmentation
        self.flip_prob = 0.5  # Horizontal flip probability
        self.hsv_prob = 0.0  # HSV augmentation probability (event cameras: 0)
        self.hsv_h = 0.0  # HSV-Hue augmentation (YOLOv8)
        self.hsv_s = 0.0  # HSV-Saturation (YOLOv8)
        self.hsv_v = 0.0  # HSV-Value (YOLOv8)
        self.mosaic = 0.0  # Mosaic augmentation probability
        self.mixup = 0.0  # Mixup augmentation probability
        
        # Validation/Testing
        self.conf_threshold = 0.001
        self.iou_threshold = 0.6
        self.val_interval = 1  # Validate every N epochs
        
        # Output
        self.project = 'runs'
        self.exp_name = 'experiment'
        
        # Device
        self.device = ''  # '' for auto, '0' for GPU 0, 'cpu' for CPU
        
        # Other
        self.verbose = True
        self.seed = 0
        self.deterministic = True
        self.exist_ok = False  # Overwrite existing experiment
        
        # Weights & Biases
        self.use_wandb = False
        self.wandb_project = 'pegma-training'
        self.wandb_name = None  # Will use exp_name if None
    
    @abstractmethod
    def to_dict(self) -> dict:
        """Convert config to dictionary for training scripts."""
        pass
    
    def __str__(self):
        """String representation of config."""
        lines = [f"{self.MODEL_TYPE.upper()} Configuration:"]
        lines.append("=" * 60)
        lines.append(f"Experiment: {self.exp_name}")
        if self.data_yaml:
            lines.append(f"Data YAML: {self.data_yaml}")
        if self.dataset_path:
            lines.append(f"Dataset: {self.dataset_path}")
        lines.append(f"Classes: {self.num_classes} ({', '.join(self.class_names)})")
        lines.append(f"Include Radar: {self.include_radar}")
        lines.append(f"Process Distance: {self.process_distance}")
        if self.process_distance:
            lines.append(f"  Distance from Head: {self.distance_from_head}")
            lines.append(f"  Distance Range: [{self.min_distance}, {self.max_distance}]m ({self.nbins} bins)")
            lines.append(f"  Distance Loss Multiplier: {self.distance_loss_multiplier}")
        lines.append(f"Epochs: {self.epochs}")
        lines.append(f"Batch Size: {self.batch_size}")
        lines.append(f"Image Size: {self.imgsz}")
        lines.append(f"Learning Rate: {self.lr0}")
        lines.append("=" * 60)
        return "\n".join(lines)


